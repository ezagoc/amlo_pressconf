"""Caption-free publication tables from saved estimates; no model changes.

Run from any directory. Requires booktabs in the paper preamble. The generated
preview is a multi-file LaTeX document, compiled from the repository root with:
pdflatex -interaction=nonstopmode -halt-on-error -output-directory=tmp/pdfs
  output/balance/latex/balance_latex_tables_preview.tex
The individual table is historical_measure ~ ask | date (observed-data samples).
The joint table is ask ~ 12 histories + missingness | date (all recorded attendees).
Both retain source-unit clustered inference from their saved fits.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DEST = ROOT / "overleaf/tables/balance"
PREVIEW = ROOT / "output/balance/latex"
DEST.mkdir(parents=True, exist_ok=True)
PREVIEW.mkdir(parents=True, exist_ok=True)


def read(path):
    with (ROOT / path).open(newline="") as f:
        return list(csv.DictReader(f))


individual = read("output/balance/historical_outcomes/individual_balance.csv")
joint = [r for r in read("output/balance/joint_by_window/joint_tests.csv") if r["test"] == "histories"]
windows = ["ratio_12m", "ratio_18m", "ratio_24m", "ratio_full"]
assert [r["window"] for r in joint] == windows
assert len(individual) == 48 and len(joint) == 4
assert len({(r["metric"], r["window"]) for r in individual}) == 48


def num(x):
    x = float(x)
    return f"{0 if abs(x) < .0005 else x:.3f}"


def pv(x):
    return r"$<0.001$" if float(x) < .001 else f"{float(x):.3f}"


def count(x):
    return f"{int(x):,}"


def row(values, extra=""):
    return " & ".join(values) + r" \\" + extra


def joint_footer():
    cells = []
    for r in joint:
        pp = r"p<0.001" if float(r["p_value"]) < .001 else "p=" + num(r["p_value"])
        cells.append(rf"\shortstack{{$F({r['df1']},{r['df2']})={num(r['F'])}$\\${pp}$}}")
    return [r"\midrule",
            row([r"\multicolumn{5}{@{}l}{Joint test of all historical covariates (7,976 outlet-days; 81 outlets)}"]),
            row([""] + cells)]


start = [
    "% Generated by code/08-results/balance/09-export_balance_latex.py.",
    "% Requires \\usepackage{booktabs}. Tabular fragment: no caption, float or notes.",
    r"\begingroup", r"\small", r"\setlength{\tabcolsep}{3pt}",
    r"\renewcommand{\arraystretch}{1.15}", r"\noindent%",
    r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lcccc@{}}", r"\toprule",
    row(["", r"\multicolumn{4}{c}{Pre-lottery measurement window}"]),
    r"\cmidrule(l){2-5}",
    row(["Historical characteristic", "12 months", "18 months", "24 months", "Full history"]),
]
end = [r"\bottomrule", r"\end{tabular*}\par", r"\endgroup", ""]
labels = {
    "question_attendance_ratio": "Questions / recorded attendance",
    "contract_value": "Contract value (MXN)",
    "contract_count": "Contracts received",
    "videos": "Videos published", "views": "Total views", "likes": "Total likes",
    "comments": "Total comments", "interactions": "Total interactions",
    "views_per_video": "Views per video", "likes_per_video": "Likes per video",
    "comments_per_video": "Comments per video", "interactions_per_video": "Interactions per video",
}
groups = [
    ("Access", "Participation history", "Raw ratio"),
    ("Contracts", "Contract histories", r"$\log(1+x)$"),
    ("YouTube", "YouTube histories", r"$\log(1+x)$"),
]
lines = start + [
    row(["", r"\multicolumn{4}{c}{\footnotesize Day-FE difference: asking $-$ nonasking [95\% CI]}"]),
    r"\midrule",
]
for family, title, transform in groups:
    rr = [r for r in individual if r["family"] == family]
    sample = {(r["n"], r["units"], r["dates"]) for r in rr}
    assert len(sample) == 1
    n, units, dates = next(iter(sample))
    lines += [r"\addlinespace[3pt]",
              row([rf"\multicolumn{{5}}{{@{{}}l}}{{\textbf{{{title}}} \quad {transform}}}"]),
              row([rf"\multicolumn{{5}}{{@{{}}l}}{{\footnotesize {count(n)} outlet-days; {units} outlets; {dates} conference dates}}"]),
              r"\addlinespace[3pt]"]
    for metric, label in labels.items():
        rrr = [r for r in rr if r["metric"] == metric]
        if not rrr:
            continue
        assert [r["window"] for r in rrr] == windows
        cells = [rf"\shortstack{{${num(r['estimate'])}$\\{{\scriptsize $[{num(r['ci_low'])},\ {num(r['ci_high'])}]$}}}}" for r in rrr]
        lines.append(row([label] + cells, "[4pt]"))
lines += [r"\midrule", row(["Conference-day fixed effects"] + ["Yes"] * 4),
          row(["SE clustering"] + ["Outlet"] * 4)] + joint_footer() + end
(DEST / "balance_individual_histories.tex").write_text("\n".join(lines))

lines = start[:-1] + [row(["Joint test", "12 months", "18 months", "24 months", "Full history"]), r"\midrule"]
assert all(int(r["df1"]) == 12 and int(r["df2"]) == 80 for r in joint)
lines = lines[:-1] + joint_footer() + end
(DEST / "balance_joint_histories.tex").write_text("\n".join(lines))

preview = r"""\documentclass[11pt]{article}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage[letterpaper,margin=0.8in]{geometry}
\usepackage{booktabs}
\pagestyle{empty}
\begin{document}
\input{overleaf/tables/balance/balance_individual_histories.tex}
\clearpage
\input{overleaf/tables/balance/balance_joint_histories.tex}
\end{document}
"""
(PREVIEW / "balance_latex_tables_preview.tex").write_text(preview)
for name in ["balance_individual_histories.tex", "balance_joint_histories.tex"]:
    output = (DEST / name).read_text()
    assert r"\caption" not in output and r"\begin{table}" not in output and "Notes:" not in output
    print(DEST / name)
print(PREVIEW / "balance_latex_tables_preview.tex")
